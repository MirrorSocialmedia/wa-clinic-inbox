const KEY_SET: ReadonlySet<string> = new Set(Object.keys(S2T));

/**
 * 簡體 → 繁體 正規化。
 * - 空字串 / 無簡體字 → 原字串（同一 reference — 快路徑零分配）。
 * - 否則逐字映射（O(n)）；表外字原樣保留。
 * 冪等：normalizeST(normalizeST(x)) === normalizeST(x)。
 */
export function normalizeST(text: string): string {
  if (!text) return text;
  let hit = false;
  for (const ch of text) {
    if (KEY_SET.has(ch)) {
      hit = true;
      break;
    }
  }
  if (!hit) return text;
  let out = "";
  for (const ch of text) out += S2T[ch] ?? ch;
  return out;
}

